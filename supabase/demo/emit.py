# Turn demo_data.json into demo_seed.sql and its exact inverse.
#
# Slugs are resolved to uuids inside the database rather than baked in here, so
# the seed keeps working if a resource is ever recreated with a new id.

import io, os, json

HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(io.open(os.path.join(HERE, 'demo_data.json'), encoding='utf-8'))

def q(s):
    if s is None: return 'NULL'
    if isinstance(s, bool): return 'true' if s else 'false'
    if isinstance(s, (int, float)): return str(s)
    return "'" + str(s).replace("'", "''") + "'"

L = []
w = L.append

w("-- Mars Space — demo floor. GENERATED by demo.py + emit.py; do not hand-edit.")
w("--")
w("-- Fills the second floor so the UI can be judged at real density: 25 offices")
w("-- let, 80 people, contracts, credit allowances, invoices, repairs and events.")
w("--")
w("-- REMOVABLE  every row uses a reserved uuid family (dc/dd/de/df/db/e1/e2), so")
w("--            demo_seed_rollback.sql removes exactly this and can never match a")
w("--            real row.")
w("-- UNDELIVERABLE  every address is @demo.mars.sa, a subdomain that does not")
w("--            resolve, so a stray notification can never reach a real person.")
w("")
w("begin;")
w("")
w("-- 1. Companies -------------------------------------------------------------")
w("insert into public.companies (id, name, name_ar, cr_number, vat_number,")
w("  billing_email, phone, status, description, description_ar, industry,")
w("  website, logo_path, is_listed) values")
w(',\n'.join('  ' + r for r in D['companies']) + ';')
w("")
w("-- The pre-existing tenant was seeded as 'DEMO — TechCorp KSA', which reads as")
w("-- placeholder text everywhere it appears. Give it a real profile. Its id and")
w("-- its membership are untouched, so the live account keeps working.")
w("update public.companies set")
w("  name = 'Thmanyah Digital', name_ar = 'ثمانية الرقمية',")
w("  description = 'Podcast and digital media production for the Arabic web.',")
w("  description_ar = 'إنتاج البودكاست والمحتوى الرقمي للويب العربي.',")
w("  industry = 'Digital Media', website = 'https://thmanyah.sa',")
w("  logo_path = 'demo/logos/office-01.png', is_listed = true")
w("where id = 'd0000000-0000-4000-8000-000000000001';")
w("")

w("-- 2. People ----------------------------------------------------------------")
w("-- profiles.id references auth.users and a trigger creates the profile row, so")
w("-- insert the auth rows first, then fill in the detail. No password is set and")
w("-- no invite is sent: these exist to populate the UI, not to be signed into.")
w("insert into auth.users (id, email) values")
w(',\n'.join(f"  ({q(p['id'])}, {q(p['email'])})" for p in D['profiles']))
w("on conflict (id) do nothing;")
w("")
w("update public.profiles p set")
w("  full_name = v.full_name, full_name_ar = v.full_name_ar, phone = v.phone,")
w("  avatar_url = v.avatar_url, preferred_language = v.lang, status = 'active',")
w("  show_in_directory = v.show_in_directory, job_title = v.job_title, bio = v.bio")
w("from (values")
w(',\n'.join(
    f"  ({q(p['id'])}::uuid, {q(p['name'])}, {q(p['name_ar'])}, {q(p['phone'])}, "
    f"{q(p['avatar'])}, {q(p['lang'])}, {q(p['show'])}, {q(p['title'])}, {q(p['bio'])})"
    for p in D['profiles']))
w(") as v(id, full_name, full_name_ar, phone, avatar_url, lang,")
w("       show_in_directory, job_title, bio)")
w("where p.id = v.id;")
w("")

w("-- 3. Contracts and offices --------------------------------------------------")
w("-- Assignments must exist before memberships: a trigger caps a company's")
w("-- members at the desks its office assignment carries, and with no assignment")
w("-- the cap is zero and every insert is refused.")
w("insert into public.contracts (id, reference, company_id, branch_id, starts_on,")
w("  ends_on, monthly_rate, credit_hours_per_period, notice_days, auto_renew, status)")
w("select v.id::uuid, v.ref, v.cid::uuid, b.id, v.starts::date, v.ends::date,")
w("       v.rate::numeric, v.credit::numeric, 60, true, 'active'")
w("from (values")
w(',\n'.join('  (' + ', '.join(q(x) for x in c) + ')' for c in D['contracts']))
w(") as v(id, ref, cid, starts, ends, rate, credit)")
w("cross join (select id from public.branches where slug = 'jeddah') b;")
w("")
w("insert into public.office_assignments (id, resource_id, company_id, contract_id,")
w("  term, desk_count, door_keycode)")
w("select v.id::uuid, r.id, v.cid::uuid, v.ctr::uuid,")
w("       daterange(v.starts::date, v.ends::date, '[)'), r.capacity, v.code")
w("from (values")
w(',\n'.join('  (' + ', '.join(q(x) for x in a) + ')' for a in D['assigns']))
w(") as v(id, slug, cid, ctr, starts, ends, code)")
w("join public.resources r on r.slug = v.slug;")
w("")

w("-- 4. Memberships ------------------------------------------------------------")
w("insert into public.company_members (company_id, profile_id, role, status,")
w("  job_title, can_book_rooms, can_view_invoices, can_submit_repairs,")
w("  can_manage_employees, joined_at) values")
w(',\n'.join('  ' + r for r in D['members']) + ';')
w("")

w("-- 5. Credit allowance for the current period ---------------------------------")
w("-- credit_period() is what create_booking() debits against, so the allocation")
w("-- has to use the same function or the balance reads as zero.")
w("insert into public.credit_entries (company_id, contract_id, period, hours,")
w("  reason, note)")
w("select v.cid::uuid, v.ctr::uuid, public.credit_period(now()), v.hours::numeric,")
w("       'plan_allocation', 'Monthly allowance'")
w("from (values")
w(',\n'.join('  (' + ', '.join(q(x) for x in c) + ')' for c in D['credits']))
w(") as v(cid, ctr, hours);")
w("")

w("-- 6. Invoices ----------------------------------------------------------------")
w("insert into public.invoices (id, invoice_number, company_id, contract_id, kind,")
w("  description, description_ar, issue_date, due_date, subtotal, vat_rate,")
w("  vat_amount, total, amount_paid, currency, status, paid_at) values")
w(',\n'.join('  ' + r for r in D['invoices']) + ';')
w("")
w("insert into public.invoice_line_items (invoice_id, description, description_ar,")
w("  quantity, unit_price, line_total, sort_order) values")
w(',\n'.join('  ' + r for r in D['lines']) + ';')
w("")

w("-- 7. Maintenance --------------------------------------------------------------")
w("insert into public.repair_requests (id, reference, company_id, reported_by,")
w("  branch_id, resource_id, category, priority, status, title, description,")
w("  created_at, resolved_at)")
w("select v.id::uuid, v.ref, v.cid::uuid, v.by::uuid, b.id, r.id,")
w("       v.cat, v.pri, v.status, v.title, v.body,")
w("       v.made::timestamptz, v.resolved::timestamptz")
w("from (values")
w(',\n'.join('  ' + r for r in D['repairs']))
w(") as v(id, ref, cid, by, slug, cat, pri, status, title, body, made, resolved)")
w("join public.resources r on r.slug = v.slug")
w("cross join (select id from public.branches where slug = 'jeddah') b;")
w("")
w("insert into public.repair_updates (repair_id, from_status, to_status, note,")
w("  created_at)")
w("select v.rid::uuid, v.frm, v.tostatus, v.note, v.at::timestamptz")
w("from (values")
w(',\n'.join('  ' + r for r in D['rep_updates']))
w(") as v(rid, frm, tostatus, note, at);")
w("")

w("-- 8. Community events ----------------------------------------------------------")
w("insert into public.events (id, slug, branch_id, resource_id, title, title_ar,")
w("  description, description_ar, time_range, capacity, status, is_public,")
w("  is_members_only, requires_registration)")
w("select v.id::uuid, v.slug, b.id, r.id, v.title, v.title_ar, v.body, v.body_ar,")
w("       tstzrange(")
w("         ((v.day::date + (v.starth || ':00')::time) at time zone 'Asia/Riyadh'),")
w("         ((v.day::date + (v.endh   || ':00')::time) at time zone 'Asia/Riyadh'),")
w("         '[)'),")
w("       v.cap::int, v.status, v.pub::boolean, not v.pub::boolean, true")
w("from (values")
w(',\n'.join('  ' + r for r in D['events']))
w(") as v(id, slug, title, title_ar, body, body_ar, day, starth, endh, status, pub, cap)")
w("join public.resources r on r.category = 'community_hall' and r.status = 'available'")
w("cross join (select id from public.branches where slug = 'jeddah') b;")
w("")
w("commit;")
w("")

io.open(os.path.join(HERE, 'demo_seed.sql'), 'w', encoding='utf-8').write('\n'.join(L))

# ---------------------------------------------------------------------------
# The exact inverse.
# ---------------------------------------------------------------------------
R = []
r = R.append
r("-- Removes everything demo_seed.sql inserted, and nothing else.")
r("--")
r("-- Every predicate keys on the reserved uuid families, never on a name or a")
r("-- status, so a real company that happens to look like demo data is safe.")
r("-- Deletion order follows the foreign keys inwards.")
r("")
r("begin;")
r("")
r("delete from public.repair_updates u using public.repair_requests q")
r("  where u.repair_id = q.id and q.id::text like 'e1000000-%';")
r("delete from public.repair_requests where id::text like 'e1000000-%';")
r("delete from public.events where id::text like 'e2000000-%';")
r("delete from public.invoice_line_items l using public.invoices i")
r("  where l.invoice_id = i.id and i.id::text like 'db000000-%';")
r("delete from public.payments p using public.invoices i")
r("  where p.invoice_id = i.id and i.id::text like 'db000000-%';")
r("delete from public.invoices where id::text like 'db000000-%';")
r("delete from public.credit_entries where company_id::text like 'dc000000-%';")
r("delete from public.bookings where company_id::text like 'dc000000-%';")
r("delete from public.company_members where company_id::text like 'dc000000-%';")
r("delete from public.office_assignments where id::text like 'de000000-%';")
r("delete from public.contracts where id::text like 'dd000000-%';")
r("delete from public.companies where id::text like 'dc000000-%';")
r("-- profiles cascade from auth.users, which is where the identity lives.")
r("delete from auth.users where id::text like 'df000000-%';")
r("")
r("-- The pre-existing tenant is left in place; only its demo styling is undone.")
r("update public.companies set logo_path = null")
r(" where id = 'd0000000-0000-4000-8000-000000000001';")
r("")
r("commit;")
r("")
io.open(os.path.join(HERE, 'demo_seed_rollback.sql'), 'w', encoding='utf-8').write('\n'.join(R))

print('demo_seed.sql        ', len('\n'.join(L)), 'bytes')
print('demo_seed_rollback.sql', len('\n'.join(R)), 'bytes')
